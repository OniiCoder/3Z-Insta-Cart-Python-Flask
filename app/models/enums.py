    DAIRY_EGGS = "DAIRY_EGGS"
    BAKERY = "BAKERY"
    BEVERAGES = "BEVERAGES"
    SNACKS = "SNACKS"
    PANTRY = "PANTRY"
    MEAT_SEAFOOD = "MEAT_SEAFOOD"
    FROZEN = "FROZEN"
    HOUSEHOLD = "HOUSEHOLD"

